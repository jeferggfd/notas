import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import os

# 1. Configuración de la página
st.set_page_config(
    page_title="Dashboard interactivo de notas",
    page_icon="📊",
    layout="wide"
)

# 2. Carga de datos con caché
@st.cache_data
def cargar_datos():
    df = pd.read_csv("estudiantes_notas.csv")
    if "Promedio" not in df.columns:
        df["Promedio"] = (df["nota_1"] + df["nota_2"]) / 2
    return df

try:
    df_original = cargar_datos()
except Exception as e:
    st.error(f"Error al cargar el archivo 'estudiantes_notas.csv': {e}")
    st.stop()

# 3. Barra lateral (Filtros y Controles)
st.sidebar.markdown("## Datos y filtros")
st.sidebar.markdown("### Carga del archivo de estudiantes")
st.sidebar.info("📂 estudiantes_notas.csv")

# Mostrar el logo institucional en la barra lateral si existe
if os.path.exists("uss logo hd.jpg"):
    st.sidebar.image("uss logo hd.jpg", use_container_width=True)

st.sidebar.markdown("---")

# Filtro de Sexo
sexos_disponibles = df_original["sexo"].unique().tolist()
sexos_seleccionados = st.sidebar.multiselect(
    "Sexo",
    options=sexos_disponibles,
    default=sexos_disponibles
)

# Filtro de Sección
secciones_disponibles = ["Todas"] + sorted(df_original["seccion"].unique().tolist())
seccion_seleccionada = st.sidebar.selectbox("Sección", options=secciones_disponibles)

# Rango de promedio (Slider)
rango_promedio = st.sidebar.slider(
    "Rango del promedio",
    min_value=1.0,
    max_value=7.0,
    value=(1.0, 7.0),
    step=0.1
)

# Asistencia mínima (%)
asistencia_minima = st.sidebar.number_input(
    "Asistencia mínima (%)",
    min_value=0,
    max_value=100,
    value=0,
    step=1
)

st.sidebar.markdown("---")
st.sidebar.caption("Los filtros se combinan. Quitar ambos sexos deja la selección vacía.")

# 4. Filtrado del DataFrame según los controles
df_filtrado = df_original.copy()

if sexos_seleccionados:
    df_filtrado = df_filtrado[df_filtrado["sexo"].isin(sexos_seleccionados)]
else:
    df_filtrado = df_filtrado.iloc[0:0]  # Vacío si no selecciona sexo

if seccion_seleccionada != "Todas":
    df_filtrado = df_filtrado[df_filtrado["seccion"] == seccion_seleccionada]

df_filtrado = df_filtrado[
    (df_filtrado["Promedio"] >= rango_promedio[0]) &
    (df_filtrado["Promedio"] <= rango_promedio[1]) &
    (df_filtrado["asistencia"] >= asistencia_minima)
]

# 5. Área Principal - Encabezado y Descripción
st.title("Dashboard interactivo de notas")
st.markdown(
    "Explora los resultados de un curso combinando filtros. **Promedio**: 50 % de cada evaluación. "
    "**Aprobación del ejercicio**: promedio mayor o igual a 4,0. Datos ficticios."
)

# Filtros activos resumidos
sexos_str = ", ".join(sexos_seleccionados) if sexos_seleccionados else "Ninguno"
st.markdown(
    f"**Filtros activos:** Sexo: `{sexos_str}` · Sección: `{seccion_seleccionada}` · "
    f"Promedio: `{rango_promedio[0]:.1f} a {rango_promedio[1]:.1f}` · Asistencia mínima: `{asistencia_minima}%`"
)

st.markdown("---")

# 6. Tarjetas de Métricas Superiores
col1, col2, col3 = st.columns(3)

with col1:
    st.markdown("Estudiantes seleccionados")
    st.markdown(f"### {len(df_filtrado)}")

with col2:
    st.markdown("Promedio general")
    prom_gral = df_filtrado["Promedio"].mean() if not df_filtrado.empty else 0.0
    st.markdown(f"### {prom_gral:.2f}".replace(".", ","))

with col3:
    st.markdown("Aprobación")
    if not df_filtrado.empty:
        aprobados = (df_filtrado["Promedio"] >= 4.0).sum()
        porcentaje_aprobacion = (aprobados / len(df_filtrado)) * 100
    else:
        porcentaje_aprobacion = 0.0
    st.markdown(f"### {porcentaje_aprobacion:.2f}%".replace(".", ","))

st.markdown("---")

# Controles de visualización
st.markdown("Gráfico")
mostrar_tabla = st.checkbox("Mostrar tabla", value=True)

# 7. Visualización (Gráfico de Barras y Tabla)
col_grafico, col_tabla = st.columns([1.2, 1])

with col_grafico:
    st.subheader("Visualización de notas")
    st.markdown("##### Promedio por estudiante")

    if not df_filtrado.empty:
        fig, ax = plt.subplots(figsize=(8, 5))

        # Gráfico de barras
        ax.bar(df_filtrado["estudiante"], df_filtrado["Promedio"], color="#1f77b4")

        # Línea horizontal de aprobación (4.0)
        ax.axhline(y=4.0, color="red", linestyle="--", label="Aprobación: 4,0")

        ax.set_ylabel("Promedio de notas")
        ax.set_xlabel("Estudiante")
        ax.set_ylim(0, 7)
        plt.xticks(rotation=35, ha="right")
        ax.legend(loc="upper right")

        st.pyplot(fig)
    else:
        st.warning("No hay datos para mostrar con los filtros seleccionados.")

with col_tabla:
    if mostrar_tabla:
        st.subheader("Estudiantes seleccionados")
        if not df_filtrado.empty:
            df_display = df_filtrado[["id", "estudiante", "sexo", "seccion", "Promedio", "asistencia"]].copy()
            df_display.columns = ["ID", "Estudiante", "Sexo", "Sección", "Promedio", "Asistencia (%)"]
            df_display["Promedio"] = df_display["Promedio"].map(lambda x: f"{x:.2f}".replace(".", ","))

            st.dataframe(df_display, hide_index=True, use_container_width=True)
        else:
            st.info("La tabla está vacía debido a los filtros actuales.")

st.markdown("---")

# 8. Botón de descarga CSV y pie de página
if not df_filtrado.empty:
    csv_data = df_filtrado.to_csv(index=False).encode("utf-8")
    st.download_button(
        label="Descargar selección CSV",
        data=csv_data,
        file_name="estudiantes_filtrados.csv",
        mime="text/csv"
    )

st.caption(f"Mostrando {len(df_filtrado)} de {len(df_original)} estudiantes. La asistencia solo se usa como filtro; la aprobación depende del promedio.")